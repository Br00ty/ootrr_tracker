"""Prepare the desktop app's build: copy the live helper's C# out of tools/live/ootrr-live.ps1.

The helper script keeps its C# inline (Add-Type -TypeDefinition @' ... '@), so players can run it with one
command. The app compiles that same code, so the script stays the only copy: this writes it to
app/obj/gen/OotrrLive.cs. Run it from anywhere before building the app (the GitHub workflow does).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, 'tools', 'live', 'ootrr-live.ps1')
OUT = os.path.join(ROOT, 'app', 'obj', 'gen', 'OotrrLive.cs')


def main():
    lines = open(SCRIPT, encoding='utf-8').read().splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.strip().startswith("Add-Type -TypeDefinition @'"))
        end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith("'@"))
    except StopIteration:
        sys.exit("tools/live/ootrr-live.ps1: couldn't find the Add-Type @' ... '@ block")
    code = lines[start + 1:end]
    if not any('class OotrrLive' in l for l in code):
        sys.exit('tools/live/ootrr-live.ps1: the Add-Type block has no OotrrLive class')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('// Generated by tools/app_sync.py from tools/live/ootrr-live.ps1: edit the script, not this file.\n')
        f.write('\n'.join(code) + '\n')
    print(f'{os.path.relpath(OUT, ROOT)}: {len(code)} lines from the helper script')
    if not os.path.exists(os.path.join(ROOT, 'index.html')):
        sys.exit('index.html is missing: run python tools/assemble.py first')


if __name__ == '__main__':
    main()
